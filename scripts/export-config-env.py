#!/usr/bin/env python3
"""infra 리포의 Terraform 출력값 → apps/parking-guardian/config.env

두 스택의 `terraform output -json` 을 읽어 config.env.example 과 같은 키 순서로 파일을 쓴다.
  network : alb_security_group_id
  data    : db_host, db_port, db_name, photos/models_bucket_name, app_fqdn, ecr_repository_urls,
            acm_certificate_arn, secret_names, db_master_secret_arn
MODEL_VERSION 은 Terraform 출력이 아니라 모델 버킷 안의 접두어(v1, v2, ...)라 인자로 받는다.

실행 전: AWS_PROFILE=parking-guardian (terraform output 이 S3 backend 의 State 를 읽는다).
  python scripts/export-config-env.py                       # infra 리포가 ../parking-guardian-infra 에 있을 때
  python scripts/export-config-env.py --infra D:/path/infra --model-version v2

이 PC 의 CRLF 문제 때문에 셸 스크립트가 아니라 Python 이다(architecture.md 6절). 출력 파일은 LF, BOM 없음.
출력 config.env 는 Git 에 커밋한다(Argo CD 가 Git 에서 빌드). 값은 식별자뿐이고 자격 증명은 Secrets Manager 에만 있다.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_ENV = REPO_ROOT / "apps" / "parking-guardian" / "config.env"


def terraform_output(stack_dir: Path) -> dict:
    """`terraform output -json` 을 실행해 {이름: 값} 으로 돌려준다."""
    if not (stack_dir / "versions.tf").exists():
        sys.exit(f"스택 폴더가 아니다: {stack_dir}")
    result = subprocess.run(
        ["terraform", f"-chdir={stack_dir}", "output", "-json"],
        capture_output=True, text=True, encoding="utf-8",
    )
    if result.returncode != 0:
        sys.exit(f"terraform output 실패 ({stack_dir.name}):\n{result.stderr}")
    raw = json.loads(result.stdout)
    if not raw:
        sys.exit(f"{stack_dir.name} 스택의 출력이 비어 있다. init/apply 가 됐는지, AWS_PROFILE 이 맞는지 확인.")
    return {k: v["value"] for k, v in raw.items()}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--infra", type=Path, default=REPO_ROOT.parent / "parking-guardian-infra",
                        help="parking-guardian-infra 리포 경로 (기본: 이 리포 옆)")
    parser.add_argument("--model-version", default="v1", help="모델 버킷 안 접두어 (기본 v1)")
    parser.add_argument("--out", type=Path, default=CONFIG_ENV, help=f"출력 파일 (기본 {CONFIG_ENV.relative_to(REPO_ROOT)})")
    args = parser.parse_args()

    if not os.environ.get("AWS_PROFILE"):
        print("경고: AWS_PROFILE 이 비어 있다. 기본 프로필(다른 계정일 수 있음)로 State 를 읽는다.", file=sys.stderr)

    stacks = args.infra / "terraform" / "stacks"
    network = terraform_output(stacks / "network")
    data = terraform_output(stacks / "data")

    # 키 순서와 이름은 config.env.example 과 같다. 바꾸면 example, 매니페스트(replacements), 이 파일을 같이 고친다.
    values = {
        # backend 가 읽는 값
        "AWS_REGION": "ap-northeast-2",
        "DB_HOST": data["db_host"],
        "DB_PORT": str(data["db_port"]),
        "DB_NAME": data["db_name"],
        "S3_BUCKET": data["photos_bucket_name"],
        "CORS_ORIGINS": f"https://{data['app_fqdn']}",
        # initContainer
        "MODELS_BUCKET": data["models_bucket_name"],
        "MODEL_VERSION": args.model_version,
        # replacements 가 매니페스트에 채우는 값
        "ECR_BACKEND": data["ecr_repository_urls"]["backend"],
        "ECR_FRONTEND": data["ecr_repository_urls"]["frontend"],
        "ECR_INFERENCE": data["ecr_repository_urls"]["inference"],  # Phase 1: data 스택에 inference 리포지토리가 있어야 한다
        "APP_HOST": data["app_fqdn"],
        "ACM_CERTIFICATE_ARN": data["acm_certificate_arn"],
        "ALB_SECURITY_GROUP_ID": network["alb_security_group_id"],
        "SECRET_NAME_APP": data["secret_names"]["app"],
        "SECRET_NAME_SEED": data["secret_names"]["seed"],
        "RDS_SECRET_ARN": data["db_master_secret_arn"],
    }

    missing = [k for k, v in values.items() if not v]
    if missing:
        sys.exit(f"값이 비어 있다: {missing}")

    lines = ["# generated by scripts/export-config-env.py. 수정하지 말고 다시 생성해 커밋한다(식별자만, 자격 증명 없음)."]
    lines += [f"{k}={v}" for k, v in values.items()]
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.out} ({len(values)} keys)")


if __name__ == "__main__":
    main()
